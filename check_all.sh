echo "=== ЗАПУСК ВСЕХ ФАЙЛОВ ИЗ PROGS ==="

for file in progs/*.h; do
    echo ""
    echo "----------------------------------------"
    echo "ФАЙЛ: $file"
    echo "----------------------------------------"
    
    # Запускаем и берем первые 5 строк вывода (или ошибки)
