#!/bin/bash
echo "=== НАЧИНАЕМ ТЕСТИРОВАНИЕ ВСЕХ ФАЙЛОВ ==="

for file in progs/*.h; do
    echo ""
    echo "----------------------------------------"
    echo "ЗАПУСК: $file"
    echo "----------------------------------------"
    # Запускаем файл и выводим первые 10 строк результата, чтобы не засорять экран
    ./h "$file" 2>&1 | head -n 15
done

echo ""
echo "=== ТЕСТИРОВАНИЕ ЗАВЕРШЕНО ==="
