#include <stdio.h>
#include <stdlib.h>
#include <string.h>

void insert_file(FILE *out, const char *filename) {
    FILE *f = fopen(filename, "r");
    if (!f) { fprintf(out, "// Cannot open %s\n", filename); return; }
    char line[1024];
    while (fgets(line, sizeof(line), f)) {
        line[strcspn(line, "\n")] = 0;
        char *p = line;
        while (*p == ' ' || *p == '\t') p++;
        if (p[0] == '\0' || p[0] == '#') continue;
        if (strncmp(p, "func ", 5) == 0) {
            char name[64]; sscanf(p + 5, "%s", name);
            fprintf(out, "void %s() {\n", name);
        } else if (strncmp(p, "end", 3) == 0) {
            fprintf(out, "}\n");
        } else if (strncmp(p, "say ", 4) == 0) {
            char *text = p + 4;
            if (text[0] == '"' || text[0] == '\'') text++;
            int len = strlen(text);
            if (len > 0 && (text[len-1] == '"' || text[len-1] == '\'')) text[len-1] = '\0';
            fprintf(out, "    uart_puts(\"%s\\n\");\n", text);
        } else if (strncmp(p, "let ", 4) == 0) {
            char var[64], expr[256]; sscanf(p + 4, "%s = %[^\n]", var, expr);
            fprintf(out, "    int %s = %s;\n", var, expr);
        }
    }
    fclose(f);
}

int main(int argc, char *argv[]) {
    if (argc < 2) { printf("Usage: hcompiler_bare <file.h>\n"); return 1; }
    FILE *in = fopen(argv[1], "r");
    if (!in) { printf("File not found\n"); return 1; }

    char out_name[256];
    strcpy(out_name, argv[1]);
    char *dot = strrchr(out_name, '.');
    if (dot) *dot = '\0';
    strcat(out_name, ".c");

    FILE *out = fopen(out_name, "w");
    if (!out) { printf("Cannot create output file\n"); return 1; }

    fprintf(out, "// Generated by hcompiler_bare\n");
    fprintf(out, "#include \"libh.h\"\n\n");
    fprintf(out, "void kernel_main() {\n");
    fprintf(out, "    char buf[256];\n    char cmd[256];\n    int i = 0;\n");

    char line[1024];
    while (fgets(line, sizeof(line), in)) {
        line[strcspn(line, "\n")] = 0;
        char *p = line;
        while (*p == ' ' || *p == '\t') p++;
        if (p[0] == '\0' || p[0] == '#') continue;

        if (strncmp(p, "use ", 4) == 0) {
            char filename[256]; sscanf(p + 4, "%s", filename);
            fprintf(out, "    // --- Included from %s ---\n", filename);
            insert_file(out, filename);
            fprintf(out, "    // --- End of %s ---\n", filename);
        }
        else if (strncmp(p, "say ", 4) == 0) {
            char *text = p + 4;
            if (text[0] == '"' || text[0] == '\'') text++;
            int len = strlen(text);
            if (len > 0 && (text[len-1] == '"' || text[len-1] == '\'')) text[len-1] = '\0';
            fprintf(out, "    uart_puts(\"%s\\n\");\n", text);
        }
        else if (strncmp(p, "say_int ", 8) == 0) {
            char var[64]; sscanf(p + 8, "%s", var);
            fprintf(out, "    say_int(%s);\n", var);
        }
        else if (strncmp(p, "let ", 4) == 0) {
            char var[64], expr[256]; sscanf(p + 4, "%s = %[^\n]", var, expr);
            // Исправлено: используем str_to_int для чисел
            if (strstr(expr, "+") != NULL) {
                char a[64], b[64]; sscanf(expr, "%s + %s", a, b);
                fprintf(out, "    int %s = str_to_int(%s) + str_to_int(%s);\n", var, a, b);
            } else if (strstr(expr, "*") != NULL) {
                char a[64], b[64]; sscanf(expr, "%s * %s", a, b);
                fprintf(out, "    int %s = str_to_int(%s) * str_to_int(%s);\n", var, a, b);
            } else {
                fprintf(out, "    int %s = %s;\n", var, expr);
            }
        }
        else if (strncmp(p, "input_str ", 10) == 0) {
            char var[64]; sscanf(p + 10, "%s", var);
            if (strcmp(var, "cmd") != 0) fprintf(out, "    char %s[256];\n", var);
            fprintf(out, "    read_string(%s, 256);\n", var);
        }
        else if (strncmp(p, "box ", 4) == 0) { int w, h; sscanf(p + 4, "%d %d", &w, &h); fprintf(out, "    draw_box(%d, %d);\n", w, h); }
        else if (strncmp(p, "clear", 5) == 0) { fprintf(out, "    clear_screen();\n"); }
        else if (strncmp(p, "color ", 6) == 0) {
            char c[32]; sscanf(p + 6, "%s", c);
            if (strcmp(c, "red") == 0) fprintf(out, "    set_color(\"\\033[31m\");\n");
            else if (strcmp(c, "green") == 0) fprintf(out, "    set_color(\"\\033[32m\");\n");
            else if (strcmp(c, "yellow") == 0) fprintf(out, "    set_color(\"\\033[33m\");\n");
            else if (strcmp(c, "blue") == 0) fprintf(out, "    set_color(\"\\033[34m\");\n");
            else if (strcmp(c, "cyan") == 0) fprintf(out, "    set_color(\"\\033[36m\");\n");
        }
        else if (strncmp(p, "reset", 5) == 0) { fprintf(out, "    reset_color();\n"); }
        else if (strncmp(p, "if ", 3) == 0 && strstr(p, "==") != NULL) {
            char var[64], val[64]; sscanf(p + 3, "%s == %s", var, val);
            if (val[0] == '"' || val[0] == '\'') val[0] = ' ';
            int len = strlen(val);
            if (len > 0 && (val[len-1] == '"' || val[len-1] == '\'')) val[len-1] = '\0';
            char *clean_val = val; while (*clean_val == ' ') clean_val++;
            fprintf(out, "    if (strcmp(%s, \"%s\") == 0) {\n", var, clean_val);
        }
        else if (strncmp(p, "else", 4) == 0) fprintf(out, "    } else {\n");
        else if (strncmp(p, "end", 3) == 0) fprintf(out, "    }\n");
        else if (strncmp(p, "while ", 6) == 0) fprintf(out, "    while (%s) {\n", p + 6);
        else if (strncmp(p, "exit", 4) == 0) fprintf(out, "    uart_puts(\"Bye!\\n\");\n    return;\n");
    }

    fprintf(out, "}\n");
    fclose(in); fclose(out);
    printf("Generated: %s\n", out_name);
    return 0;
}
